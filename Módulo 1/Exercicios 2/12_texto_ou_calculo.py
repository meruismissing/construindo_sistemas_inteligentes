print("12 + 3") # Mostrará como resultado os números por extenso, assim como estão escritos na linha de código. Ex: "12 + 3"
print(12 + 3) # Mostrará o resultado do cálculo, pois não conta como string, ou seja, é um número
print("Resultado:", 12 + 3) 
print("12", "3")
# Os resultados se diferem porque em um, existe uma string, que é as aspas entre o texto, e no outro é um cálculo de verdade, o que se chama de number, que vai direto ao ponto e mostra o resultado sem precisar de print("15"), exemplo que foi dado ali mesmo: print("Resultado:", 12 + 3)
