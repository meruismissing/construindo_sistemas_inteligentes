nome_da_oficina = "Robótica para Iniciantes"
sala = "Laboratório 2"
quantidade_vagas = 24
duracao_horas = 2.5
inscricoes_abertas = True

print(nome_da_oficina, type(nome_da_oficina)) # Nesse contexto, string é o nome da oficina, que é um texto.
print(sala, type(sala)) # Nesse contexto, é uma string também pois é um texto e o número conta também como texto pois está dentro da string e não fora. str significa string
print(quantidade_vagas, type(quantidade_vagas)) # Nesse contexto, int é o número da sala, que é um number, sem ponto flutuante. int é Inteiro
print(duracao_horas, type(duracao_horas)) # Nesse contexto, float é para ponto flutuante, quando é um número que têm casas decimais. float significa Ponto Flutuante
print(inscricoes_abertas, type(inscricoes_abertas)) # Neste contexto, bool é para uma variável que pode assumir só dois significados, True or False. bool significa booleano
